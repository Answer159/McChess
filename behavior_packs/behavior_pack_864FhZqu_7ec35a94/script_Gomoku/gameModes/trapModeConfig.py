# -*- coding: utf-8 -*-
# =====================================================================
# 陷阱模式配置 —— 这个模式的全部可调数值都在这里，trapMode.py 里零硬编码。
# 与主 config.py 的分工：主 config 管"五子棋本体"（棋盘/道具/刷新表），
# 本文件只管"陷阱模式自己的地形与陷阱规则"。关掉模式只需把
# config.GameMode 改回 "classic"，本文件的值就完全不生效。
#
# 一句话玩法：地面原样不动（本图陷阱区地表是基岩，挖不动），棋盘外随机
# 长出几条通往道具生成点的安全路，路外的格子是陷阱——踩上去脚下的地表
# 方块临时换成岩浆、掉血、被弹回上一个安全格，岩浆N秒后复原回原方块。
# =====================================================================

# ---------------------- 陷阱区范围 ----------------------
# 陷阱区半边长（格，切比雪夫方形）：以棋盘中心为中心的 (2*AreaRadius+1) 见方
# 内会撒生成点、长路、判陷阱（纯脚本数据，一格方块都不动）。范围外还是
# 原生地形（跑出去就没有陷阱了，也不会再有本模式的资源点）
AreaRadius = 15
# 棋盘外的安全圈宽度（格）：棋盘见方往外这么多圈永远安全，
# 既是"棋盘外面2圈都是实的"，也是复活点与弹回兜底点所在。
# ★须 >= 1；与棋盘半边长相加须 < AreaRadius，否则整张陷阱区都是安全区
SafeRingWidth = 2

# ---------------------- 地面与岩浆（不动地形，只做方块临时替换） ----------------------
# 地面：保持地图原样——不整平、不铺伪装层（本图陷阱区地表本来就是基岩，
# 玩家挖不动，不存在"挖土打洞绕过雷区"的问题）
# 踩中陷阱后该列地表方块临时变成的方块
LavaBlockName = "minecraft:lava"
# 复原目标：触发时记下原方块名换回去；查询失败退回这个方块（本图即基岩）
RestoreFallbackBlockName = "minecraft:bedrock"
# 地表高度查询失败时的立足面高度（棋盘基座层Y + 本偏移；1 = 与站上棋盘齐平）
FallbackFootYOffset = 1

# ---------------------- 道具生成点与路径 ----------------------
# 生成多少个道具生成点（每个生成点各自长一条路通回棋盘安全区）。
# ★数量、间距、环距带要一起算账：(13,15)环距带共约336格，间距3时每点
# 占掉约25格，上限约13个——要再加密就得放宽间距或扩大环距带
SpawnPointCount = 10
# 生成点距棋盘中心的环距范围（格，切比雪夫）。★会被自动夹进
# [安全圈外沿+1, AreaRadius]，写超了不会报错，只会被夹住
SpawnPointRadiusRange = (13, 15)
# 两个生成点之间的最小间距（格，切比雪夫）：太近的点会被跳过，
# 免得几条路挤在一起。放不下这么多点时就少放几个（不会死循环）
SpawnPointMinGap = 3
# 生成点不做任何标记：场上除玩法道具（矿石/棋子/物品/问号方块）外
# 一律不放其他方块，玩家靠路径上刷出的资源认路
# 路径宽度（格）：1 = 单格独木桥。★偶数会向下取到相邻奇数
# （有效宽度 = 2*((PathWidth-1)//2)+1），所以有意义的取值是 1/3/5
PathWidth = 1
# 每走一步换轴（拐弯）的概率 0~1：0 = 先把一个方向走完再走另一个（两段直角），
# 0.5 = 锯齿状；越小路越"直"、越好认
PathTurnChance = 0.35

# ---------------------- 踩雷判定与惩罚 ----------------------
# 岩浆持续多少秒后复原成触发前的原方块（复原后这格仍然是陷阱，只是又看不出来了）
LavaRestoreSeconds = 3
# 踩一次陷阱掉多少血（点数，2 点 = 1 颗心）
StepDamage = 4
# 触发的高度带（格）：脚底高出该列地表不超过这么多才算"踩上去"。
# 1.6 > 原版跳跃峰值约 1.25，所以蹦跳/疾跑跳也躲不过陷阱；
# 想允许"跳过一格陷阱"就把这个值调到 1.2 以下
TriggerMaxHeight = 1.6
# 每隔多少帧检查一次全体玩家脚下（30帧=1秒）：1 = 每帧查（最灵敏也最费），
# 2 ≈ 每 1/15 秒，够跟上跑动速度
CheckIntervalFrames = 2
# 同一名玩家的提示（踩雷/禁止放置）最短间隔（秒），防刷屏
TipCooldownSeconds = 2
# 重生落地（PlayerRespawnFinishServerEvent）后延迟多少帧把玩家拉回棋盘边
# 安全圈：LimitedRespawn在同事件的回调里会把人传到队伍复活点（经典模式的
# 复活位置，离棋盘很远），跨mod监听顺序不保证谁先被调，晚它几帧稳定压过；
# 传送失败（刚落地组件未就绪等）再等 RespawnTeleportRetryFrames 帧重试一次
RespawnFinishTeleportFrames = 3
RespawnTeleportRetryFrames = 15

# ---------------------- 进场与开局落位 ----------------------
# 进图落位：世界出生点在远处未加载区块，刚进图的玩家离棋盘很远。进图后延迟
# JoinTeleportDelayFrames 帧查一次位置，离棋盘超过 JoinTeleportRing（格，
# 切比雪夫环距）就把人直接拉进棋盘安全圈（棋盘周围SafeRingWidth圈内）。
# ★阈值必须大于等待区（约35格）与两队落点（16~31格）的距离，否则会把
# 大厅等待/队伍落位的玩家也拉走，破坏StartLogic的流程
JoinTeleportRing = 50
# 进图传送的延迟帧数（30帧=1秒）：等玩家实体加载完、坐标可读
JoinTeleportDelayFrames = 30
# 开局落位：StartLogic开局会把玩家传到各自的队伍落点（都在陷阱区外），
# 陷阱模式等 RoundStartTeleportDelayFrames 帧后再把全体拉进棋盘安全圈，
# 开局就站在棋盘边上而不是隔着整片雷区（30帧=1秒）
RoundStartTeleportDelayFrames = 45

# ---------------------- 资源刷新的适配 ----------------------
# True = 刷新落点要求该列地表"实心可站"：宿主的 FindSurfaceY 含树叶，
# 不过滤的话矿石/道具会刷在树冠顶上，玩家根本够不着。过滤规则=
# 该列地表方块名不含 NonGroundBlockKeywords 里任何一词（结果按格缓存，
# 一格一局只查一次）。正冒岩浆的列也会被顺带滤掉（方块名变lava了）
SpawnRequireSolidGround = True
# 不算"实心地面"的地表方块关键词（对方块名做包含匹配）：
# 树叶/树干顶上站不住，水面/岩浆上更是落不了
NonGroundBlockKeywords = ("leaves", "log", "water", "lava")
# True = 把主 config 里各刷新环的半径按比例重映射进陷阱区
# （见 trapMode.MapRing）：源区间 SpawnRadiusSourceRange 里的
# "近/中/远"被压缩到 [安全圈外沿+1, AreaRadius] 这段，保住"越远越值钱"的
# 层次感，同时保证所有资源都落在陷阱区内的安全格上。
# False = 不重映射，直接把环半径夹进陷阱区（外环会全挤在最外圈）
RemapSpawnRadius = True
# 重映射的源区间（格）：主 config 里最近的环内半径 ~ 最远的环外半径
# （现为 ItemTierDict low 的 5 到 high 的 35）。★改了主 config 的环半径后
# 顺手对一下这两个数，否则映射会偏
SpawnRadiusSourceRange = (5, 35)
